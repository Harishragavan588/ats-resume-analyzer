"""
services/report_service.py — Generate a downloadable PDF analysis report.
Uses reportlab for PDF generation (no external API required).
"""

import logging
from io import BytesIO
from datetime import datetime
from typing import Dict, Any

logger = logging.getLogger(__name__)


def generate_pdf_report(analysis_data: Dict[str, Any]) -> bytes:
    """
    Generate a PDF report from an analysis dict.

    Args:
        analysis_data : dict as returned by Analysis.to_dict()

    Returns:
        Raw PDF bytes.
    """
    try:
        from reportlab.lib.pagesizes import A4  # type: ignore
        from reportlab.lib import colors  # type: ignore
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle  # type: ignore
        from reportlab.lib.units import cm  # type: ignore
        from reportlab.platypus import (  # type: ignore
            SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable,
        )

        buffer = BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=A4,
            rightMargin=2 * cm,
            leftMargin=2 * cm,
            topMargin=2 * cm,
            bottomMargin=2 * cm,
        )

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            "Title",
            parent=styles["Heading1"],
            fontSize=20,
            textColor=colors.HexColor("#1a56db"),
            spaceAfter=6,
        )
        h2_style = ParagraphStyle(
            "H2",
            parent=styles["Heading2"],
            fontSize=13,
            textColor=colors.HexColor("#1e3a5f"),
            spaceAfter=4,
        )
        body_style = styles["Normal"]
        body_style.fontSize = 10

        story = []

        # Header
        story.append(Paragraph("ATS Resume Analyzer — Analysis Report", title_style))
        story.append(Paragraph(
            "DISCLAIMER: This is an estimated match score generated by this application. "
            "It is NOT an official ATS score.",
            ParagraphStyle("Disclaimer", parent=body_style, textColor=colors.red, fontSize=9),
        ))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#1a56db")))
        story.append(Spacer(1, 0.3 * cm))

        # Meta
        created = analysis_data.get("created_at", "")
        if created:
            try:
                created = datetime.fromisoformat(created).strftime("%Y-%m-%d %H:%M UTC")
            except Exception:
                pass
        story.append(Paragraph(f"<b>File:</b> {analysis_data.get('original_filename', 'N/A')}", body_style))
        story.append(Paragraph(f"<b>Analysed:</b> {created}", body_style))
        story.append(Spacer(1, 0.4 * cm))

        # Score summary table
        story.append(Paragraph("Score Summary", h2_style))
        breakdown = analysis_data.get("score_breakdown", {})
        score_data = [
            ["Component", "Weight", "Score"],
            ["Keyword Match", "40%", f"{breakdown.get('keyword_match', 0):.1f}"],
            ["Text Similarity", "30%", f"{breakdown.get('similarity', 0):.1f}"],
            ["Experience Signals", "20%", f"{breakdown.get('experience', 0):.1f}"],
            ["Formatting", "10%", f"{breakdown.get('formatting', 0):.1f}"],
            ["TOTAL ATS SCORE", "100%", f"{analysis_data.get('ats_score', 0):.1f}"],
        ]
        table = Table(score_data, colWidths=[8 * cm, 3 * cm, 3 * cm])
        table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1a56db")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 10),
            ("ROWBACKGROUNDS", (0, 1), (-1, -2), [colors.white, colors.HexColor("#eef3fb")]),
            ("BACKGROUND", (0, -1), (-1, -1), colors.HexColor("#1e3a5f")),
            ("TEXTCOLOR", (0, -1), (-1, -1), colors.white),
            ("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold"),
            ("ALIGN", (1, 0), (-1, -1), "CENTER"),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.lightgrey),
            ("ROWPADDING", (0, 0), (-1, -1), 5),
        ]))
        story.append(table)
        story.append(Spacer(1, 0.5 * cm))

        # Matched keywords
        story.append(Paragraph("Matched Keywords", h2_style))
        matched = analysis_data.get("matched_keywords", [])
        story.append(Paragraph(
            ", ".join(matched) if matched else "None detected.",
            body_style,
        ))
        story.append(Spacer(1, 0.3 * cm))

        # Missing keywords
        story.append(Paragraph("Missing Keywords", h2_style))
        missing = analysis_data.get("missing_keywords", [])
        story.append(Paragraph(
            ", ".join(missing) if missing else "None — great coverage!",
            body_style,
        ))
        story.append(Spacer(1, 0.3 * cm))

        # Suggestions
        story.append(Paragraph("Improvement Suggestions", h2_style))
        for i, suggestion in enumerate(analysis_data.get("suggestions", []), 1):
            story.append(Paragraph(f"{i}. {suggestion}", body_style))
        story.append(Spacer(1, 0.3 * cm))

        # Predicted category
        category = analysis_data.get("predicted_category")
        if category:
            story.append(Paragraph("Detected Job Category", h2_style))
            story.append(Paragraph(
                f"{category} <i>(automated estimate — see disclaimer above)</i>",
                body_style,
            ))

        doc.build(story)
        pdf_bytes = buffer.getvalue()
        buffer.close()
        logger.info("PDF report generated: %d bytes", len(pdf_bytes))
        return pdf_bytes

    except ImportError:
        logger.error("reportlab is not installed. Cannot generate PDF report.")
        raise RuntimeError(
            "PDF report generation requires 'reportlab'. "
            "Run: pip install reportlab"
        )
    except Exception as exc:
        logger.exception("PDF generation failed: %s", exc)
        raise RuntimeError(f"Failed to generate report: {exc}") from exc
